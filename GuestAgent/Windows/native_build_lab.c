static int codec_roundtrips(void) {
    for (size_t i = 0; i < sizeof(vectors) / sizeof(vectors[0]); ++i) {
        mvo_agent_frame frame;
        unsigned char output[128];
        if (!mvo_agent_decode(vectors[i].bytes, vectors[i].count, &frame)) return 0;
        size_t count = mvo_agent_encode(&frame, output, sizeof(output));
        if (count != vectors[i].count) return 0;
        for (size_t j = 0; j < count; ++j) if (output[j] != vectors[i].bytes[j]) return 0;
    }
    return 1;
}

__declspec(noreturn) void mvo_start(void) {
    if (!codec_roundtrips()) ExitProcess(10);
    PSecPkgInfoW package = NULL;
    SECURITY_STATUS status = QuerySecurityPackageInfoW(UNISP_NAME_W, &package);
    if (status != SEC_E_OK || package == NULL) ExitProcess(11);
    if (package->cbMaxToken == 0 || package->cbMaxToken > 65536u) {
        FreeContextBuffer(package);
        ExitProcess(12);
    }
    if (FreeContextBuffer(package) != SEC_E_OK) ExitProcess(13);
    HCERTSTORE store = CertOpenStore(CERT_STORE_PROV_MEMORY, 0, (HCRYPTPROV_LEGACY)0,
                                    CERT_STORE_CREATE_NEW_FLAG, NULL);
    if (store == NULL || !CertCloseStore(store, 0)) ExitProcess(14);
    OVERLAPPED pending;
    memset(&pending, 0, sizeof(pending));
    pending.hEvent = CreateEventW(NULL, TRUE, FALSE, NULL);
    if (pending.hEvent == NULL) ExitProcess(15);
    int handles = SetEvent(pending.hEvent) && WaitForSingleObject(pending.hEvent, 0) == WAIT_OBJECT_0 &&
                  ResetEvent(pending.hEvent) && CloseHandle(pending.hEvent);
    if (!handles) ExitProcess(16);
    static const char message[] = "mvo.windows-native-smoke codec=1 provider=1 empty-store=1 event=1\r\n";
    DWORD written = 0;
    HANDLE output = GetStdHandle(STD_OUTPUT_HANDLE);
    if (output == NULL || output == INVALID_HANDLE_VALUE ||
        !WriteFile(output, message, (DWORD)(sizeof(message) - 1u), &written, NULL) ||
        written != sizeof(message) - 1u) ExitProcess(17);
    ExitProcess(0);
}
