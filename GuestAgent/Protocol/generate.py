"""Generate fixed-width v1 Swift/C codecs and shared vectors from the reviewed schema."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = Path(__file__).with_name("schema.json")
WIDTH = {"bytes16": 16, "u16": 2, "u32": 4, "u64": 8}
SWIFT = {"bytes16": "Data", "u16": "UInt16", "u32": "UInt32", "u64": "UInt64"}
C = {"bytes16": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "u64": "uint64_t"}


def snake(name):
    first = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first).lower()


def render(schema):
    messages = schema["messages"]
    common = schema["commonFields"]
    assert schema["major"] == 1 and schema["minor"] == 0
    assert 16 <= schema["maximumFrameBytes"] <= 4096
    assert len({m["id"] for m in messages}) == len(messages)
    for message in messages:
        assert re.fullmatch(r"[a-z][a-zA-Z0-9]*", message["name"])
        fields = common + message["fields"]
        assert len({f["name"] for f in fields}) == len(fields)
        for field in fields:
            assert re.fullmatch(r"[a-z][a-zA-Z0-9]*", field["name"])
            assert field["type"] in WIDTH
        message["allFields"] = fields
        message["size"] = sum(WIDTH[f["type"]] for f in fields)
        assert 16 + message["size"] <= schema["maximumFrameBytes"]
    digest = hashlib.sha256(SCHEMA.read_bytes()).hexdigest()
    swift = ["// SPDX-License-Identifier: Apache-2.0", "// Generated by GuestAgent/Protocol/generate.py; do not edit.",
             "// Schema SHA-256: " + digest, "import Foundation", ""]
    for m in messages:
        name = "Agent" + m["name"][0].upper() + m["name"][1:]
        m["swiftName"] = name
        swift.append(f"public struct {name}: Equatable, Sendable {{")
        swift += [f"  public var {f['name']}: {SWIFT[f['type']]}" for f in m["allFields"]]
        arguments = ", ".join(f"{f['name']}: {SWIFT[f['type']]}" for f in m["allFields"])
        swift.append(f"  public init({arguments}) {{")
        swift += [f"    self.{f['name']} = {f['name']}" for f in m["allFields"]]
        swift += ["  }", "}", ""]
    swift += ["public enum AgentV1Message: Equatable, Sendable {"]
    swift += [f"  case {m['name']}({m['swiftName']})" for m in messages]
    swift += ["}", "", "public struct AgentV1Decoded: Equatable, Sendable {",
              "  public let minor: UInt16", "  public let message: AgentV1Message", "}",
              "public enum AgentV1CodecError: Error, Equatable, Sendable { case malformedFrame }",
              "public enum AgentV1Codec {", "  public static let headerBytes = 16",
              f"  public static let maximumFrameBytes = {schema['maximumFrameBytes']}",
              f"  public static let healthFeature: UInt32 = {schema['features']['health']}",
              "  public static func frameLength(header: Data) throws -> Int {",
              "    let bytes = Array(header)", "    guard bytes.count == headerBytes else { throw AgentV1CodecError.malformedFrame }",
              f"    guard get(bytes, 0, 4) == {schema['magic']}, get(bytes, 4, 2) == 1, get(bytes, 10, 2) == 0 else {{ throw AgentV1CodecError.malformedFrame }}",
              "    let body: Int", "    switch get(bytes, 8, 2) {"]
    swift += [f"    case {m['id']}: body = {m['size']}" for m in messages]
    swift += ["    default: throw AgentV1CodecError.malformedFrame", "    }",
              "    guard get(bytes, 12, 4) == UInt64(body) else { throw AgentV1CodecError.malformedFrame }",
              "    return headerBytes + body", "  }",
              "  public static func encode(_ message: AgentV1Message, minor: UInt16 = 0) throws -> Data {",
              "    var bytes: [UInt8] = []", f"    put({schema['magic']}, 4, &bytes)",
              "    put(1, 2, &bytes)", "    put(UInt64(minor), 2, &bytes)", "    switch message {"]
    for m in messages:
        swift += [f"    case .{m['name']}(let value):", f"      put({m['id']}, 2, &bytes)",
                  "      put(0, 2, &bytes)", f"      put({m['size']}, 4, &bytes)"]
        for f in m["allFields"]:
            if f["type"] == "bytes16":
                swift += [f"      guard value.{f['name']}.count == 16 else {{ throw AgentV1CodecError.malformedFrame }}",
                          f"      bytes.append(contentsOf: value.{f['name']})"]
            else:
                swift.append(f"      put(UInt64(value.{f['name']}), {WIDTH[f['type']]}, &bytes)")
    swift += ["    }", "    return Data(bytes)", "  }",
              "  public static func decode(_ data: Data) throws -> AgentV1Decoded {",
              "    guard data.count >= headerBytes, data.count <= maximumFrameBytes else { throw AgentV1CodecError.malformedFrame }",
              "    let bytes = Array(data)", "    let length = try frameLength(header: Data(bytes.prefix(headerBytes)))",
              "    guard data.count == length else { throw AgentV1CodecError.malformedFrame }",
              "    let message: AgentV1Message", "    switch get(bytes, 8, 2) {"]
    for m in messages:
        parts, offset = [], 16
        for f in m["allFields"]:
            width = WIDTH[f["type"]]
            value = f"Data(bytes[{offset}..<{offset + width}])" if f["type"] == "bytes16" else f"{SWIFT[f['type']]}(get(bytes, {offset}, {width}))"
            parts.append(f"{f['name']}: {value}")
            offset += width
        swift.append(f"    case {m['id']}: message = .{m['name']}(.init({', '.join(parts)}))")
    swift += ["    default: throw AgentV1CodecError.malformedFrame", "    }",
              "    return AgentV1Decoded(minor: UInt16(get(bytes, 6, 2)), message: message)", "  }",
              "  private static func get(_ bytes: [UInt8], _ offset: Int, _ width: Int) -> UInt64 {",
              "    var value: UInt64 = 0", "    for byte in bytes[offset..<(offset + width)] { value = (value << 8) | UInt64(byte) }",
              "    return value", "  }",
              "  private static func put(_ value: UInt64, _ width: Int, _ bytes: inout [UInt8]) {",
              "    for index in (0..<width).reversed() { bytes.append(UInt8(truncatingIfNeeded: value >> (index * 8))) }",
              "  }", "}"]
    c = ["/* SPDX-License-Identifier: Apache-2.0 */", "/* Generated by generate.py; do not edit. */",
         "/* Schema SHA-256: " + digest + " */", "#ifndef MVO_AGENT_V1_H", "#define MVO_AGENT_V1_H",
         "#include <stdint.h>", "#include <stddef.h>", "#include <string.h>",
         f"#define MVO_AGENT_MAGIC UINT32_C({schema['magic']})", "#define MVO_AGENT_HEADER_BYTES 16u",
         f"#define MVO_AGENT_MAX_FRAME_BYTES {schema['maximumFrameBytes']}u", "#define MVO_AGENT_FEATURE_HEALTH 1u"]
    for m in messages:
        m["cName"] = snake(m["name"])
        c.append(f"#define MVO_AGENT_{m['cName'].upper()} {m['id']}u")
        c.append("typedef struct {")
        for f in m["allFields"]:
            suffix = "[16]" if f["type"] == "bytes16" else ""
            c.append(f"    {C[f['type']]} {snake(f['name'])}{suffix};")
        c.append(f"}} mvo_agent_{m['cName']};")
    c += ["typedef struct {", "    uint16_t minor;", "    uint16_t kind;", "    union {"]
    c += [f"        mvo_agent_{m['cName']} {m['cName']};" for m in messages]
    c += ["    } body;", "} mvo_agent_frame;",
          "static inline uint64_t mvo_agent_get(const uint8_t *p, size_t width) {",
          "    uint64_t value = 0; for (size_t i = 0; i < width; ++i) value = (value << 8) | p[i]; return value;", "}",
          "static inline void mvo_agent_put(uint8_t *p, uint64_t value, size_t width) {",
          "    for (size_t i = 0; i < width; ++i) p[i] = (uint8_t)(value >> ((width - 1 - i) * 8));", "}",
          "static inline size_t mvo_agent_frame_length(const uint8_t *p, size_t count) {",
          "    if (!p || count < 16 || mvo_agent_get(p, 4) != MVO_AGENT_MAGIC || mvo_agent_get(p + 4, 2) != 1 || mvo_agent_get(p + 10, 2) != 0) return 0;",
          "    size_t body; switch (mvo_agent_get(p + 8, 2)) {"]
    c += [f"    case {m['id']}: body = {m['size']}; break;" for m in messages]
    c += ["    default: return 0;", "    }",
          "    return mvo_agent_get(p + 12, 4) == body ? body + 16 : 0;", "}",
          "static inline int mvo_agent_decode(const uint8_t *p, size_t count, mvo_agent_frame *out) {",
          "    size_t length = mvo_agent_frame_length(p, count);",
          "    if (!out || !length || count != length) return 0;", "    memset(out, 0, sizeof(*out));",
          "    out->minor = (uint16_t)mvo_agent_get(p + 6, 2); out->kind = (uint16_t)mvo_agent_get(p + 8, 2);",
          "    switch (out->kind) {"]
    for m in messages:
        c.append(f"    case {m['id']}:")
        offset = 16
        for f in m["allFields"]:
            destination = f"out->body.{m['cName']}.{snake(f['name'])}"
            if f["type"] == "bytes16":
                c.append(f"        memcpy({destination}, p + {offset}, 16);")
            else:
                c.append(f"        {destination} = ({C[f['type']]})mvo_agent_get(p + {offset}, {WIDTH[f['type']]});")
            offset += WIDTH[f["type"]]
        c.append("        break;")
    c += ["    default: return 0;", "    }", "    return 1;", "}",
          "static inline size_t mvo_agent_encode(const mvo_agent_frame *frame, uint8_t *p, size_t capacity) {",
          "    if (!frame || !p) return 0;", "    size_t body; switch (frame->kind) {"]
    c += [f"    case {m['id']}: body = {m['size']}; break;" for m in messages]
    c += ["    default: return 0;", "    }", "    if (capacity < body + 16) return 0;",
          "    mvo_agent_put(p, MVO_AGENT_MAGIC, 4); mvo_agent_put(p + 4, 1, 2); mvo_agent_put(p + 6, frame->minor, 2);",
          "    mvo_agent_put(p + 8, frame->kind, 2); mvo_agent_put(p + 10, 0, 2); mvo_agent_put(p + 12, body, 4);",
          "    switch (frame->kind) {"]
    for m in messages:
        c.append(f"    case {m['id']}:")
        offset = 16
        for f in m["allFields"]:
            value = f"frame->body.{m['cName']}.{snake(f['name'])}"
            if f["type"] == "bytes16":
                c.append(f"        memcpy(p + {offset}, {value}, 16);")
            else:
                c.append(f"        mvo_agent_put(p + {offset}, {value}, {WIDTH[f['type']]});")
            offset += WIDTH[f["type"]]
        c.append("        break;")
    c += ["    default: return 0;", "    }", "    return body + 16;", "}", "#endif"]
    vectors = []
    for m in messages:
        body, values = bytearray(), {}
        for f in m["allFields"]:
            if f["type"] == "bytes16":
                value = bytes(range(16)); body.extend(value); values[f["name"]] = value.hex()
            else:
                value = {"u16": 0x0203, "u32": 0x01020304, "u64": 0x0102030405060708}[f["type"]]
                body.extend(value.to_bytes(WIDTH[f["type"]], "big")); values[f["name"]] = value
        header = struct.pack(">IHHHHI", schema["magic"], 1, 0, m["id"], 0, len(body))
        vectors.append(dict(name=m["name"], fields=values, frameHex=(header + body).hex()))
    return "\n".join(swift) + "\n", "\n".join(c) + "\n", json.dumps(vectors, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    swift, c, vectors = render(json.loads(SCHEMA.read_text()))
    with tempfile.TemporaryDirectory(prefix="mvo-agent-generation-") as temporary:
        path = Path(temporary) / "Generated.swift"
        path.write_text(swift)
        subprocess.run(["xcrun", "swift-format", "format", "--in-place", str(path)], check=True)
        swift = path.read_text()
    outputs = {
        ROOT / "GuestAgent/Host/GeneratedAgentMessages.swift": swift,
        ROOT / "GuestAgent/Protocol/generated/agent_v1.h": c,
        ROOT / "Tests/AgentProtocolTests/vectors.json": vectors,
    }
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit("Generated agent protocol is stale: " + path.name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Agent Swift/C codecs and vectors match the schema" if args.check else "Generated agent Swift/C codecs and vectors")


if __name__ == "__main__":
    main()
