@MainActor private final class MediaAdmissionPreferences: VMLibraryPreferences {
  var data: Data?
  func read() throws -> Data? { data }
  func write(_ data: Data) throws { self.data = data }
}

@MainActor private final class MediaAdmissionWindow: NSWindow {
  var activationRequests = 0
  override func makeKeyAndOrderFront(_ sender: Any?) { activationRequests += 1 }
}

/// The pause follows an actual ordinary Core write and its actual exclusive backup.
@MainActor private final class ControlledMediaSettings: DesktopMediaSettingsUpdating {
  var calls = 0
  var holdCompletion = true
  var failAfterCommit = false
  var committed: VMConfiguration?
  var pending: CheckedContinuation<Void, Never>?

  func update(
    in directory: URL, expected: VMConfiguration, selected: URL?, support: Bool
  ) async throws -> VMConfiguration {
    calls += 1
    let result = try await NativeDesktopMediaSettings().update(
      in: directory, expected: expected, selected: selected, support: support)
    committed = result
    if holdCompletion { await withCheckedContinuation { pending = $0 } }
    if failAfterCommit { throw NSError(domain: "private post-commit media fixture", code: 1) }
    return result
  }

  func release() {
    let continuation = pending
    pending = nil
    continuation?.resume()
  }
}

/// Always unavailable; it never returns a verified image or any runtime authority.
@MainActor private final class ControlledUnavailableDriverDisc: DesktopWindowsDriverDiscPreparing {
  var calls = 0
  var released = false
  var pending: CheckedContinuation<Void, Never>?

  func imageURL(accelerated: Bool, displayExperiment: Bool) async throws -> URL {
    calls += 1
    if !released { await withCheckedContinuation { pending = $0 } }
    throw NSError(domain: "private unavailable media catalog", code: 1)
  }

  func release() {
    released = true
    let continuation = pending
    pending = nil
    continuation?.resume()
  }
}

/// Real hidden sessions and disposable Core metadata only; no panels, activation or VM.
@MainActor @Suite(.serialized) struct DesktopMediaAdmissionTests {
  enum Kind: CaseIterable, Sendable { case installation, support }
  enum Completion: CaseIterable, Sendable {
    case ownerSuccess, ownerFailure, replacementSuccess, replacementFailure
    var replacesSelection: Bool { self == .replacementSuccess || self == .replacementFailure }
    var fails: Bool { self == .ownerFailure || self == .replacementFailure }
  }
  private struct Fixture {
    let root: URL
    let directory: URL
    let selected: URL
    let original: VMConfiguration
    let bytes: Data
    var registration: URL { directory.appendingPathComponent("configuration.json") }
  }

  private func fixture(windows: Bool = false) async throws -> Fixture {
    let root = FileManager.default.temporaryDirectory.resolvingSymlinksInPath()
      .appendingPathComponent("media-admission-\(UUID().uuidString)")
    let directory = root.appendingPathComponent("fixture.macopenvm", isDirectory: true)
    try FileManager.default.createDirectory(
      at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    let selected = root.appendingPathComponent("generated-fixture.iso")
    // Regular aligned generated bytes; no ISO/filesystem/architecture claim.
    try Data(repeating: 0x52, count: 1024).write(to: selected)
    try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: selected.path)
    let original = VMConfiguration(
      name: "Media editor", guest: windows ? .windows11 : .linux,
      backend: windows ? .qemuHVF : .appleVz, cpuCount: windows ? 2 : 1,
      memoryBytes: windows ? 4 << 30 : 512 << 20, diskBytes: windows ? 64 << 30 : 1 << 30)
    var bytes = try ConfigurationCodec.encode(original)
    bytes.append(Data("\n\n".utf8))
    let files = VMFiles()
    try await files.atomicWrite(bytes, at: directory.appendingPathComponent("configuration.json"))
    if !windows {
      try await files.createSparseDisk(
        at: directory.appendingPathComponent("disk.raw"), bytes: 1 << 30)
    }
    return Fixture(
      root: root, directory: directory, selected: selected, original: original, bytes: bytes)
  }

  private func window() -> MediaAdmissionWindow {
    let owner = MediaAdmissionWindow(
      contentRect: NSRect(x: 0, y: 0, width: 600, height: 500),
      styleMask: [.titled], backing: .buffered, defer: false)
    owner.isReleasedWhenClosed = false
    return owner
  }

  private func selected(
    _ fixture: Fixture, service: ControlledMediaSettings,
    catalog: any DesktopWindowsDriverDiscPreparing = NativeDesktopWindowsDriverDiscPreparation()
  ) async throws -> (DesktopSession, MediaAdmissionWindow) {
    _ = NSApplication.shared
    let owner = window()
    let session = DesktopSession(
      library: VMLibrary(preferences: MediaAdmissionPreferences()),
      graphicsPreferences: WindowsGraphicsPreferenceStore(
        preferences: MemoryWindowsGraphicsPreferences()),
      mediaSettings: service, driverDiscPreparation: catalog)
    session.window = owner
    try await session.qualificationSelectVM(
      at: fixture.registration, expectedID: fixture.original.id)
    #expect(session.configuration == fixture.original && !session.isBusy)
    #expect(session.selectedConfigurationURL == fixture.registration)
    return (session, owner)
  }

  private func change(_ kind: Kind, to url: URL?, session: DesktopSession) {
    if kind == .installation {
      session.changeInstallationMedia(url)
    } else {
      session.changeSupportMedia(url)
    }
  }

  private func settle(_ session: DesktopSession) async throws {
    let deadline = ContinuousClock.now + .seconds(4)
    while session.preparing && ContinuousClock.now < deadline {
      try await Task.sleep(for: .milliseconds(10))
    }
    #expect(!session.preparing)
  }

  private func entered(_ service: ControlledMediaSettings) async throws {
    let deadline = ContinuousClock.now + .seconds(4)
    while service.pending == nil && ContinuousClock.now < deadline {
      try await Task.sleep(for: .milliseconds(10))
    }
    #expect(service.pending != nil && service.committed != nil)
  }

  private func drainUnexpectedWriter(_ service: ControlledMediaSettings, session: DesktopSession)
    async throws
  {
    let deadline = ContinuousClock.now + .seconds(4)
    while session.preparing && service.pending == nil && ContinuousClock.now < deadline {
      try await Task.sleep(for: .milliseconds(10))
    }
    service.release()
    try await settle(session)
  }

  private func backup(_ kind: Kind, in fixture: Fixture) throws -> [URL] {
    let prefix =
      kind == .installation ? "configuration-media-backup-" : "configuration-support-media-backup-"
    return try FileManager.default.contentsOfDirectory(
      at: fixture.directory, includingPropertiesForKeys: nil
    )
    .filter { $0.lastPathComponent.hasPrefix(prefix) }
  }

  private func requireFirstBackup(_ kind: Kind, fixture: Fixture) throws {
    let backups = try backup(kind, in: fixture)
    #expect(backups.count == 1)
    let backup = try #require(backups.first)
    #expect(try Data(contentsOf: backup) == fixture.bytes)
  }

  @Test(arguments: Kind.allCases, ["owner-aba", "selection-aba"])
  func queuedMediaWriteCannotReuseAnOldOwnerOrSelection(kind: Kind, change: String) async throws {
    let fixture = try await fixture()
    defer { try? FileManager.default.removeItem(at: fixture.root) }
    let service = ControlledMediaSettings()
    defer {
      service.holdCompletion = false
      service.release()
    }
    let (session, owner) = try await selected(fixture, service: service)
    let replacement = window()
    let names = try FileManager.default.contentsOfDirectory(atPath: fixture.directory.path).sorted()
    self.change(kind, to: fixture.selected, session: session)
    #expect(session.preparing)
    if change == "owner-aba" {
      session.window = replacement
      session.window = owner
    } else {
      var changed = fixture.original
      changed.name = "Temporary selection"
      session.configuration = changed
      session.configuration = fixture.original
    }
    try await drainUnexpectedWriter(service, session: session)
    #expect(service.calls == 0 && session.configuration == fixture.original)
    #expect(try Data(contentsOf: fixture.registration) == fixture.bytes)
    #expect(
      try FileManager.default.contentsOfDirectory(atPath: fixture.directory.path).sorted() == names)
    service.holdCompletion = false
    self.change(kind, to: fixture.selected, session: session)
    try await settle(session)
    #expect(service.calls == 1 && session.configuration == service.committed)
    try requireFirstBackup(kind, fixture: fixture)
    #expect(owner.activationRequests == 0 && replacement.activationRequests == 0)
    withExtendedLifetime((owner, replacement)) {}
  }

  @Test(arguments: Kind.allCases, Completion.allCases)
  func staleMediaCompletionPreservesCommittedBytesAndUnrelatedReplacement(
    kind: Kind, completion: Completion
  ) async throws {
    let fixture = try await fixture()
    defer { try? FileManager.default.removeItem(at: fixture.root) }
    let service = ControlledMediaSettings()
    defer {
      service.holdCompletion = false
      service.release()
    }
    service.failAfterCommit = completion.fails
    let (session, owner) = try await selected(fixture, service: service)
    let replacementOwner = window()
    self.change(kind, to: fixture.selected, session: session)
    try await entered(service)
    let committed = try #require(service.committed)
    #expect(try ConfigurationCodec.decode(Data(contentsOf: fixture.registration)) == committed)
    try requireFirstBackup(kind, fixture: fixture)
    var replacement = fixture.original
    replacement.id = UUID()
    replacement.name = "Independent replacement"
    let replacementBytes = try ConfigurationCodec.encode(replacement)
    if !completion.replacesSelection {
      session.window = replacementOwner
      session.window = owner
    } else {
      try await VMFiles().atomicWrite(replacementBytes, at: fixture.registration)
      session.configuration = replacement
      session.errorMessage = "Newer independent message"
    }
    service.release()
    try await settle(session)
    if !completion.replacesSelection {
      #expect(session.configuration == nil && session.selectedConfigurationURL == nil)
      #expect(try ConfigurationCodec.decode(Data(contentsOf: fixture.registration)) == committed)
      #expect(session.errorMessage != nil)
    } else {
      #expect(
        session.configuration == replacement
          && session.selectedConfigurationURL == fixture.registration)
      #expect(try Data(contentsOf: fixture.registration) == replacementBytes)
      #expect(session.errorMessage == "Newer independent message")
    }
    #expect(session.errorMessage?.contains("private post-commit media fixture") == false)
    try requireFirstBackup(kind, fixture: fixture)
    #expect(owner.activationRequests == 0 && replacementOwner.activationRequests == 0)
    withExtendedLifetime((owner, replacementOwner)) {}
  }

  @Test(arguments: Kind.allCases, [false, true])
  func uncertainCurrentMediaCommitKeepsItsWarningWithoutReplacingANewerError(
    kind: Kind, newerError: Bool
  ) async throws {
    let fixture = try await fixture()
    defer { try? FileManager.default.removeItem(at: fixture.root) }
    let service = ControlledMediaSettings()
    defer {
      service.holdCompletion = false
      service.release()
    }
    service.failAfterCommit = true
    let (session, owner) = try await selected(fixture, service: service)
    change(kind, to: fixture.selected, session: session)
    try await entered(service)
    let committed = try #require(service.committed)
    if newerError { session.errorMessage = "Newer independent message" }
    service.release()
    try await settle(session)
    #expect(session.configuration == nil && session.selectedConfigurationURL == nil)
    #expect(!session.canStartSelected && session.errorMessage != nil)
    if newerError { #expect(session.errorMessage == "Newer independent message") }
    #expect(session.errorMessage?.contains("private post-commit media fixture") == false)
    #expect(try ConfigurationCodec.decode(Data(contentsOf: fixture.registration)) == committed)
    try requireFirstBackup(kind, fixture: fixture)
    withExtendedLifetime(owner) {}
  }

  @Test(arguments: Kind.allCases)
  func currentMediaCommitPreservesANewerErrorAndAllowsExplicitDetach(kind: Kind) async throws {
    let fixture = try await fixture()
    defer { try? FileManager.default.removeItem(at: fixture.root) }
    let service = ControlledMediaSettings()
    defer {
      service.holdCompletion = false
      service.release()
    }
    let (session, owner) = try await selected(fixture, service: service)
    change(kind, to: fixture.selected, session: session)
    try await entered(service)
    let committed = try #require(service.committed)
    let committedBytes = try Data(contentsOf: fixture.registration)
    session.errorMessage = "Newer independent message"
    service.release()
    try await settle(session)
    #expect(
      session.configuration == committed && session.errorMessage == "Newer independent message")
    try requireFirstBackup(kind, fixture: fixture)
    service.holdCompletion = false
    change(kind, to: nil, session: session)
    try await settle(session)
    #expect(service.calls == 2 && session.configuration == fixture.original)
    #expect(session.errorMessage == "Newer independent message")
    #expect(
      try ConfigurationCodec.decode(Data(contentsOf: fixture.registration)) == fixture.original)
    let backups = try backup(kind, in: fixture)
    let saved = try backups.map { try Data(contentsOf: $0) }
    #expect(saved.count == 2 && saved.contains(fixture.bytes) && saved.contains(committedBytes))
    #expect(owner.activationRequests == 0)
    withExtendedLifetime(owner) {}
  }

  @Test(arguments: ["owner-aba", "selection-aba"], [false, true])
  func unavailableWindowsDriverCatalogCannotWriteThroughAStaleRequest(
    change: String, beforeCatalog: Bool
  ) async throws {
    let fixture = try await fixture(windows: true)
    defer { try? FileManager.default.removeItem(at: fixture.root) }
    let service = ControlledMediaSettings()
    defer {
      service.holdCompletion = false
      service.release()
    }
    let catalog = ControlledUnavailableDriverDisc()
    defer { catalog.release() }
    let (session, owner) = try await selected(fixture, service: service, catalog: catalog)
    let replacement = window()
    session.chooseSupportMedia()
    #expect(session.preparing)
    if !beforeCatalog {
      let deadline = ContinuousClock.now + .seconds(4)
      while catalog.pending == nil && ContinuousClock.now < deadline {
        try await Task.sleep(for: .milliseconds(10))
      }
      #expect(catalog.pending != nil && catalog.calls == 1)
    }
    if change == "owner-aba" {
      session.window = replacement
      session.window = owner
    } else {
      var changed = fixture.original
      changed.name = "Temporary selection"
      session.configuration = changed
      session.configuration = fixture.original
    }
    catalog.release()
    try await settle(session)
    #expect(catalog.calls == (beforeCatalog ? 0 : 1))
    #expect(service.calls == 0 && session.configuration == fixture.original)
    #expect(session.selectedConfigurationURL == fixture.registration && session.errorMessage == nil)
    #expect(try Data(contentsOf: fixture.registration) == fixture.bytes)
    #expect(owner.activationRequests == 0 && replacement.activationRequests == 0)
    withExtendedLifetime((owner, replacement)) {}
  }
}
