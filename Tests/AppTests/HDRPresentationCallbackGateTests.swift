import Foundation
import Qemu
import Testing

@testable import MacOpenVMApp

struct HDRPresentationCallbackGateTests {
  @Test func lateRetiredAndOldActivationCallbacksCannotResetPresentationProgress() throws {
    let frame = try message()
    let owner = HDRPresentationCallbackGate.Owner()
    var gate = HDRPresentationCallbackGate(first: frame, owner: owner)
    #expect(gate.ticket(for: frame) == nil)
    gate.setActive(true)
    let first = try #require(gate.ticket(for: frame))
    #expect(gate.accepts(first, message: frame, currentOwner: owner))
    gate.setActive(true)
    #expect(gate.accepts(first, message: frame, currentOwner: owner))
    gate.setActive(false)
    #expect(!gate.accepts(first, message: frame, currentOwner: owner))
    gate.setActive(true)
    #expect(!gate.accepts(first, message: frame, currentOwner: owner))
    let resumed = try #require(gate.ticket(for: frame))
    #expect(gate.accepts(resumed, message: frame, currentOwner: owner))
    gate.retire()
    gate.setActive(true)
    #expect(gate.ticket(for: frame) == nil)
    #expect(!gate.accepts(resumed, message: frame, currentOwner: owner))
  }

  @Test func currentInputTransportControllerAndExactDrawnFrameAreAllRequired() throws {
    let frame = try message()
    let owner = HDRPresentationCallbackGate.Owner()
    var gate = HDRPresentationCallbackGate(first: frame, owner: owner)
    gate.setActive(true)
    let ticket = try #require(gate.ticket(for: frame))
    let foreign = [
      HDRPresentationCallbackGate.Owner(
        controllerID: UUID(),
        inputConnectionEpoch: owner.inputConnectionEpoch,
        transportConnectionEpoch: owner.transportConnectionEpoch),
      HDRPresentationCallbackGate.Owner(
        controllerID: owner.controllerID,
        inputConnectionEpoch: UUID(), transportConnectionEpoch: owner.transportConnectionEpoch),
      HDRPresentationCallbackGate.Owner(
        controllerID: owner.controllerID,
        inputConnectionEpoch: owner.inputConnectionEpoch, transportConnectionEpoch: UUID()),
    ]
    for changed in foreign {
      #expect(!gate.accepts(ticket, message: frame, currentOwner: changed))
    }
    let later = try message(sequence: 2, content: 2)
    #expect(!gate.accepts(ticket, message: later, currentOwner: owner))
    var replacement = HDRPresentationCallbackGate(first: frame, owner: owner)
    replacement.setActive(true)
    #expect(!replacement.accepts(ticket, message: frame, currentOwner: owner))
  }

  @Test func wrongStreamOrColorProfileCannotIssueOrReuseADrawableTicket() throws {
    let frame = try message()
    let owner = HDRPresentationCallbackGate.Owner()
    var gate = HDRPresentationCallbackGate(first: frame, owner: owner)
    gate.setActive(true)
    let ticket = try #require(gate.ticket(for: frame))
    for changed in [try message(epoch: 2), try message(color: 2), try message(target: 1)] {
      #expect(gate.ticket(for: changed) == nil)
      #expect(!gate.accepts(ticket, message: changed, currentOwner: owner))
    }
    // A legal backbuffer/selection rotation keeps the surface profile, but a
    // callback still carries the exact immutable frame that was submitted.
    let rotation = try message(sequence: 2, content: 2, resource: 2, incarnation: 2, selection: 2)
    let rotated = try #require(gate.ticket(for: rotation))
    #expect(gate.accepts(rotated, message: rotation, currentOwner: owner))
    #expect(!gate.accepts(ticket, message: rotation, currentOwner: owner))
  }

  /// Independent generated bytes are admitted by the production C-backed
  /// HDRFrameMessage parser. No socket, GPU, layer or source capability exists.
  private func message(
    sequence: UInt64 = 1, content: UInt64 = 1, resource: UInt64 = 1,
    incarnation: UInt64 = 1, selection: UInt64 = 1, color: UInt64 = 1,
    epoch: UInt8 = 1, target: UInt64 = 0
  ) throws -> HDRFrameMessage {
    var packet = Data(repeating: 0, count: 128)
    func put(_ value: UInt64, _ offset: Int, _ count: Int) {
      for index in 0..<count {
        packet[offset + index] = UInt8(truncatingIfNeeded: value >> (index * 8))
      }
    }
    put(0x3248_564d, 0, 4)
    put(2, 4, 2)
    put(3, 6, 2)
    packet.replaceSubrange(8..<24, with: repeatElement(epoch, count: 16))
    put(sequence, 24, 8)
    put(content, 32, 8)
    put(incarnation, 40, 8)
    put(color, 48, 8)
    put(selection, 56, 8)
    put(resource, 64, 4)
    put(31, 72, 4)
    put(3, 76, 4)
    put(256, 80, 4)
    put(4096, 84, 4)
    put((sequence - 1) % 2, 88, 4)
    put(2, 92, 4)
    put(1, 96, 4)
    put(80_000, 100, 4)
    put(1, 104, 8)
    put(target, 116, 4)
    return try HDRFrameMessage(admitting: packet, limits: HDRFrameLimits(pageBytes: 4096))
  }
}
